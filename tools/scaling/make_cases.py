#!/usr/bin/env python3
"""Generate the cases used for scaling measurements.

    python3 tools/scaling/make_cases.py            # write to cases/scaling/
    python3 tools/scaling/make_cases.py --check    # only check that existing files match

The generated cases use the same physics and the same input keys as the
regression cases in cases/, but **three things are changed for the sake of
the measurement**.

  (1) Automatic time-step control is switched off so that the step size is
      fixed ([Numerics.TimeStepControl] Enable = false).
      With automatic control the history of step sizes can diverge through
      rounding differences between backends, so the amount of work would
      vary from run to run.
  (2) The number of steps is fixed (Numerics.MaxSteps), with EndTime placed
      out of reach. The measurement then answers "how many seconds for the
      same work".
  (3) Field output is switched off (NeutralFile / VTKFile = false, output
      intervals set enormous). The output interval also acts as an upper
      bound on the time step, so making it small would change the step size
      as well. Keeping it enormous also avoids measuring I/O time.

The sequence of grid sizes is there to vary the "work per thread" and so
show how the efficiency behaves. Filling 112 cores requires a
correspondingly large problem. The guide is the block decomposition of the
Vector reduction,

    number of blocks = min(256, number of elements / 512)

so for blocks to reach all 112 threads the element count must be
>= 512*112 = 57,344, and for the load to approach uniformity
>= 512*256 = 131,072. The two-dimensional 512^2 = 262,144 and the
one-dimensional Nx=131072 are at that level.

Copyright 2017-2026 Suguru Shiratori, Tokyo City University
SPDX-License-Identifier: Apache-2.0
"""

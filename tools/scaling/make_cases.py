#---------------------------------------------------------------------------
#  Case table
#
#  dt has been chosen **from measurements**, so that Newton converges in
#  2-3 iterations at every size. Get this wrong and Newton stalls (more than
#  10 iterations per step), and what is measured is no longer "parallel
#  performance" but "poor convergence". Refining the grid sharply lowers the
#  explicit stability limit dt_exp ~ 3 mu dx^4 / H^3, which raises the floor
#  on the Newton correction (~ eps_mach * dt/dt_exp); dt therefore has to
#  fall as dx^2 in two dimensions, and even more steeply in one dimension
#  (dx^4 is still not enough there. The coupling with the concentration
#   equation is presumably responsible, but here we simply follow the
#   measurements).
#
#  steps has been chosen so that the single-thread run time stays within
#  practical bounds. Measured guide values (development machine: Xeon
#  2.80 GHz, 1 thread, Release + AMGCL).
#
#     case            1 step [s] eigen   1 step [s] amgcl
#     1d n2000            0.013            0.011
#     1d n8000            0.036            0.33
#     1d n32000           0.14             1.06
#     1d n131072          0.78             3.06
#     2d 128^2            --               0.64
#     2d 256^2            --               2.59
#     2d 512^2            --               13.3
#     2d 1024^2           --               ~70
#
#  To change the number of steps, edit this table and regenerate
#  (scaling.sh does not rewrite the inputs).
#---------------------------------------------------------------------------
CASES_1D = [
    #  name             Nx        dt         steps   tier
    ("bench1d_n02000",  2000,     2.0e-5,    2000,   "quick"),
    ("bench1d_n08000",  8000,     7.81e-8,   200,    "quick"),
    ("bench1d_n032000", 32000,    3.0e-11,   60,     "full"),
    ("bench1d_n131072", 131072,   1.2e-14,   30,     "full"),
]

CASES_2D = [
    #  name             N         dt         steps   tier
    ("bench2d_n0128",   128,      2.0e-4,    100,    "quick"),
    ("bench2d_n0256",   256,      5.0e-5,    40,     "quick"),
    ("bench2d_n0512",   512,      1.25e-5,   12,     "full"),
    ("bench2d_n1024",   1024,     3.1e-6,    4,      "full"),
]


def one_case(name, dim, nx, ny, dt, steps, note):
    txt = HEADER.format(name=name, job=name, note=note)
    txt += GRID.format(dim=dim, nx=nx, ny=ny,
                       xmin="-0.5e-3", xmax="0.5e-3",
                       ymin=("-1" if dim == "xh" else "-0.5e-3"),
                       ymax=("1" if dim == "xh" else "0.5e-3"))
    txt += INITIAL_1D
    txt += FLUID
    txt += PHYSICS
    txt += OUTPUT
    txt += NUMERICS.format(dt=repr(dt), steps=steps)
    return txt


MANIFEST = "manifest.tsv"
MANIFEST_HEAD = "case\tdim\tnx\tny\tnodes\tdt\tsteps\ttier\n"


def build_all():
    """Return {filename: contents}. manifest.tsv is included in the same dict."""
    out = {}
    rows = [MANIFEST_HEAD]
    for name, nx, dt, steps, tier in CASES_1D:
        note = ("1-D, Nx = %d (%d unknowns), %d steps, tier=%s"
                % (nx, nx, steps, tier))
        out[name + ".toml"] = one_case(name, "xh", nx, 1, dt, steps, note)
        rows.append("%s\t1\t%d\t1\t%d\t%s\t%d\t%s\n"
                    % (name, nx, nx, repr(dt), steps, tier))
    for name, n, dt, steps, tier in CASES_2D:
        note = ("2-D, %dx%d (%d unknowns), %d steps, tier=%s"
                % (n, n, n * n, steps, tier))
        out[name + ".toml"] = one_case(name, "xyh", n, n, dt, steps, note)
        rows.append("%s\t2\t%d\t%d\t%d\t%s\t%d\t%s\n"
                    % (name, n, n, n * n, repr(dt), steps, tier))
    #  scaling.sh reads this to obtain the case list and its metadata.
    out[MANIFEST] = "".join(rows)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="write nothing; fail if a file on disk differs")
    ap.add_argument("--outdir", default=OUTDIR)
    args = ap.parse_args()

    cases = build_all()
    if args.check:
        bad = 0
        for fname, txt in sorted(cases.items()):
            p = os.path.join(args.outdir, fname)
            if not os.path.exists(p):
                print("MISSING  %s" % p)
                bad += 1
            elif open(p, encoding="utf-8").read() != txt:
                print("DIFFERS  %s" % p)
                bad += 1
        if bad:
            sys.exit(1)
        print("check: %d files match" % len(cases))
        return

    os.makedirs(args.outdir, exist_ok=True)
    for fname, txt in sorted(cases.items()):
        p = os.path.join(args.outdir, fname)
        with open(p, "w", encoding="utf-8") as f:
            f.write(txt)
        print("wrote %s" % os.path.relpath(p, ROOT))


if __name__ == "__main__":
    main()
